import { z } from 'zod';

export const createEventSchema = z.object({
  eventName: z.string().trim().min(3, 'Event name must be at least 3 characters').max(200, 'Event name cannot exceed 200 characters'),
  description: z.string().optional().nullable(),
  category: z.string().trim().min(1, 'Category is required'),
  eventType: z.string().trim().min(1, 'Event type is required'),
  collegeName: z.string().optional().nullable(),
  departmentName: z.string().optional().nullable(),
  eventDate: z.string().min(1, 'Event date is required'),
  eventTime: z.string().min(1, 'Event time is required'),
  endDate: z.string().optional().nullable(),
  endTime: z.string().optional().nullable(),
  registrationDeadline: z.string().optional().nullable(),
  venueName: z.string().optional().nullable(),
  location: z.string().optional().nullable(),
  googleMapsUrl: z.string().url('Google Maps URL must be a valid URL').or(z.literal('')).optional().nullable(),
  whatsappGroupLink: z.string().url('WhatsApp group link must be a valid URL').or(z.literal('')).optional().nullable(),
  whatsappContactNumber: z.string().max(30).optional().nullable(),
  venueLatitude: z.number().optional().nullable(),
  venueLongitude: z.number().optional().nullable(),
  ticketPrice: z.number().min(0, 'Ticket price cannot be negative').default(0),
  memberTicketPrice: z.number().min(0, 'Member ticket price cannot be negative').optional().nullable(),
  totalSeats: z.number().int().min(1, 'Total seats must be at least 1'),
  volunteerCapacity: z.number().int().min(0).optional().nullable(),
  volunteerCategories: z.union([z.string(), z.array(z.string())]).optional().nullable(),
  status: z.enum(['DRAFT', 'PUBLISHED', 'PENDING_APPROVAL']).default('PUBLISHED').optional(),
  visibility: z.enum(['PUBLIC', 'PRIVATE']).default('PUBLIC').optional(),
  tags: z.union([z.string(), z.array(z.string())]).optional().nullable(),
  organizerDetails: z.string().optional().nullable(),
  authorizedDocumentUrl: z.string().optional().nullable(),
  hasCertificate: z.boolean().default(false).optional(),
  certificateSettings: z.object({
    certificateAvailable: z.boolean().optional(),
    automaticGeneration: z.boolean().optional(),
    releaseMode: z.enum(['MANUAL', 'AUTOMATIC', 'SCHEDULED']).optional(),
    releaseDate: z.string().optional().nullable(),
    minimumAttendanceRequired: z.boolean().optional(),
    certificateType: z.string().optional(),
    organizerName: z.string().optional().nullable(),
    organizationName: z.string().optional().nullable(),
    verificationBaseUrl: z.string().optional().nullable(),
    certificateExpiry: z.string().optional().nullable(),
    theme: z.string().optional().nullable(),
  }).optional().nullable(),

  // Food & Accommodation
  foodProvided: z.boolean().optional(),
  foodMeals: z.string().optional().nullable(),
  foodType: z.string().optional().nullable(),
  teaCoffeeProvided: z.boolean().optional(),
  specialDiet: z.string().optional().nullable(),
  accommodationProvided: z.boolean().optional(),
  accommodationType: z.string().optional().nullable(),
  accommodationCharges: z.number().int().optional().nullable(),
  accommodationBedsAvailable: z.number().int().optional().nullable(),
  accommodationDetails: z.any().optional().nullable(),
  boysHostelAvailable: z.boolean().optional(),
  girlsHostelAvailable: z.boolean().optional(),
  hotelTieupAvailable: z.boolean().optional(),
  accommodationCheckIn: z.string().optional().nullable(),
  accommodationCheckOut: z.string().optional().nullable(),
  accommodationContactPerson: z.string().optional().nullable(),

  // Transportation & Facilities
  nearestBusStop: z.string().optional().nullable(),
  distanceFromBusStop: z.string().optional().nullable(),
  busNumbers: z.string().optional().nullable(),
  nearestRailwayStation: z.string().optional().nullable(),
  distanceFromRailwayStation: z.string().optional().nullable(),
  nearestAirport: z.string().optional().nullable(),
  metroInformation: z.string().optional().nullable(),
  landmarks: z.string().optional().nullable(),
  parkingAvailable: z.string().optional().nullable(),
  travelGuide: z.string().optional().nullable(),
  estimatedTravelTime: z.string().optional().nullable(),
  cabEstimate: z.string().optional().nullable(),
  nearbyHotels: z.string().optional().nullable(),
  nearbyRestaurants: z.string().optional().nullable(),
  emergencyContacts: z.string().optional().nullable(),
  sessionSchedule: z.string().optional().nullable(),
  speakerList: z.string().optional().nullable(),
  liveAnnouncements: z.string().optional().nullable(),
  reportingTime: z.string().optional().nullable(),
  dressCode: z.string().optional().nullable(),
  itemsToBring: z.string().optional().nullable(),
  laptopRequired: z.boolean().optional(),
  idCardRequired: z.boolean().optional(),
  teamSize: z.string().optional().nullable(),
  rules: z.string().optional().nullable(),
  refundPolicy: z.string().optional().nullable(),
  cancellationPolicy: z.string().optional().nullable(),
  certificateEligibility: z.string().optional().nullable(),
  wifiAvailable: z.boolean().optional(),
  medicalSupportAvailable: z.boolean().optional(),
});

export const updateEventSchema = createEventSchema.partial().extend({
  eventName: z.string().trim().min(3).max(200).optional(),
});

export const eventSearchQuerySchema = z.object({
  keyword: z.string().optional(),
  category: z.string().optional(),
  eventType: z.string().optional(),
  location: z.string().optional(),
  collegeName: z.string().optional(),
  departmentName: z.string().optional(),
  venueName: z.string().optional(),
  organizerName: z.string().optional(),
  dateFrom: z.string().optional(),
  dateTo: z.string().optional(),
  priceMin: z.coerce.number().optional(),
  priceMax: z.coerce.number().optional(),
  freeOnly: z.enum(['true', 'false']).transform((v) => v === 'true').or(z.boolean()).optional(),
  paidOnly: z.enum(['true', 'false']).transform((v) => v === 'true').or(z.boolean()).optional(),
  interCollege: z.enum(['true', 'false']).transform((v) => v === 'true').or(z.boolean()).optional(),
  intraCollege: z.enum(['true', 'false']).transform((v) => v === 'true').or(z.boolean()).optional(),
  past: z.enum(['true', 'false']).transform((v) => v === 'true').or(z.boolean()).optional(),
  sortBy: z.string().default('date_asc'),
  page: z.coerce.number().int().min(0).default(0),
  size: z.coerce.number().int().min(1).max(100).default(12),
});

export const approvalDecisionSchema = z.object({
  decision: z.enum(['APPROVE', 'REJECT', 'REQUEST_MODIFICATIONS'], {
    errorMap: () => ({ message: 'Decision must be APPROVE, REJECT, or REQUEST_MODIFICATIONS' }),
  }),
  reason: z.string().optional().nullable(),
});

export const eventAnnouncementSchema = z.object({
  title: z.string().trim().min(1, 'Title is required').max(200),
  message: z.string().trim().min(1, 'Message is required'),
  notifyVolunteers: z.boolean().optional().default(false),
});

